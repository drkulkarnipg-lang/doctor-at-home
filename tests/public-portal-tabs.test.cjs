'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const html = fs.readFileSync('index.html', 'utf8');
const script = fs.readFileSync('public-portal-tabs.js', 'utf8');
const awareness = fs.readFileSync('awareness-library.js', 'utf8');
assert.doesNotMatch(awareness, /healthGlobalSearchForm/, 'Global article search must submit to /articles, not be intercepted as local guide filtering.');
assert.match(html,/patientTabs\.classList\.toggle\('hidden', type !== 'public'\)/,'Patient tabs must be hidden while Doctor Workstation is active.');
const dom = new JSDOM(html, { url: 'https://clinic.example.test/', runScripts: 'outside-only' });
const w = dom.window, d = w.document;
w.eval(script);
d.dispatchEvent(new w.Event('DOMContentLoaded'));
const panels = [...d.querySelectorAll('#publicPortal [data-public-panel]')];
const tabs = [...d.querySelectorAll('.portal-nav [role="tab"]')];
const visible = () => panels.filter(p => !p.hidden);
assert.equal(panels.length, 7);
assert.equal(tabs.length, 7);
assert.deepEqual(visible().map(p => p.id), ['portalPanelOverview']);
for (const key of ['elderly','library','search','booking','tools','faq','overview']) {
  const tab = d.querySelector('[data-public-tab="'+key+'"]');
  tab.dispatchEvent(new w.MouseEvent('click', { bubbles: true, cancelable: true }));
  assert.equal(visible().length, 1, key+' tab must show exactly one panel');
  assert.equal(visible()[0].id, tab.getAttribute('aria-controls'));
  assert.equal(tab.getAttribute('aria-selected'), 'true');
  assert.equal(tab.tabIndex, 0);
}
assert.equal(d.getElementById('publicGuidanceSection').closest('[data-public-panel]').id, 'portalPanelLibrary');
assert.equal(d.getElementById('exploreHealthResources').closest('[data-public-panel]').id, 'portalPanelLibrary');
assert.equal(d.getElementById('nutritionSection').closest('[data-public-panel]').id, 'portalPanelElderly');
assert.equal(d.getElementById('healthGlobalSearchForm').closest('[data-public-panel]').id, 'portalPanelSearch');
assert.equal(d.getElementById('onlineConsultationNotice').closest('[data-public-panel]').id, 'portalPanelBooking');
assert.equal(d.getElementById('bookingSection').closest('[data-public-panel]').id, 'portalPanelBooking');
assert.equal(d.getElementById('patientToolsSection').closest('[data-public-panel]').id, 'portalPanelTools');
assert.equal(d.getElementById('patientFaq').closest('[data-public-panel]').id, 'portalPanelFaq');
assert.equal(d.querySelector('.care-pathways a')?.getAttribute('href'), '#elderlySection', 'Elderly care pathway must open elderly care, not booking.');
const directChildren = [...d.getElementById('publicPortal').children];
assert.ok(directChildren.every(child => child.hasAttribute('data-public-panel')), 'All Patient Portal content belongs to one of the seven panels.');
w.switchPublicTab('overview');
d.querySelector('.hero-primary-actions a[href="#bookingSection"]').dispatchEvent(new w.MouseEvent('click', { bubbles: true, cancelable: true }));
assert.deepEqual(visible().map(p => p.id), ['portalPanelBooking'], 'Home-visit CTA must activate booking panel.');
w.switchPublicTab('overview');
d.querySelector('.care-pathways a[href="#elderlySection"]').dispatchEvent(new w.MouseEvent('click', { bubbles: true, cancelable: true }));
assert.deepEqual(visible().map(p => p.id), ['portalPanelElderly'], 'Elderly pathway must activate elderly panel.');
const keyboardTab = d.querySelector('[data-public-tab="overview"]');
keyboardTab.focus();
keyboardTab.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true, cancelable: true }));
assert.equal(d.activeElement.dataset.publicTab, 'elderly', 'Arrow keys move focus to the next tab.');
assert.equal(d.querySelector('[data-public-tab="elderly"]').getAttribute('aria-selected'), 'true');
w.switchPublicTab('booking');
assert.deepEqual(visible().map(p => p.id), ['portalPanelBooking']);
dom.window.close();
const direct = new JSDOM(html, { url: 'https://clinic.example.test/#bookingSection', runScripts: 'outside-only' });
direct.window.eval(script);
direct.window.document.dispatchEvent(new direct.window.Event('DOMContentLoaded'));
assert.deepEqual([...direct.window.document.querySelectorAll('[data-public-panel]')].filter(p => !p.hidden).map(p => p.id), ['portalPanelBooking'], 'Direct section URLs must open the owning tab.');
direct.window.close();
console.log('Seven Patient Portal tabs, single-panel visibility, article grouping, CTA targets, keyboard and deep-link checks passed.');
