'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const api=fs.readFileSync(path.join(root,'api/clinical-cloud.js'),'utf8');
const cloud=fs.readFileSync(path.join(root,'cloud-records.js'),'utf8');
const ui=fs.readFileSync(path.join(root,'workstation-registers.js'),'utf8');
const migration=fs.readdirSync(path.join(root,'supabase/migrations')).filter(x=>x.includes('clinic_document_vault'));
assert.ok(migration.length===1,'A versioned document vault migration must exist.');
for(const id of ['clinicDocumentVault','vaultTitle','vaultType','vaultFile','vaultUpload','vaultRefresh','vaultRows'])assert.match(html,new RegExp('id="'+id+'"'),'Vault UI element '+id+' must exist.');
for(const action of ['documents-list','document-upload','document-download'])assert.ok(api.includes("action==='"+action+"'"),'Server must implement '+action);
assert.match(api,/clinic-document-vault/,'Documents must use the private storage bucket.');
assert.match(api,/owner_id:user\.id/,'Document metadata must be owner scoped.');
assert.match(api,/createHash\('sha256'\)/,'Server must verify document integrity.');
assert.match(api,/bytes\.length>7864320/,'Server must enforce upload size limit.');
assert.match(api,/storage\/v1\/object\/sign/,'Downloads must use short-lived signed URLs.');
for(const method of ['listDocuments','uploadDocument','downloadDocument'])assert.match(cloud,new RegExp(method+':async'),'Cloud client must expose '+method);
for(const fn of ['vaultSave','vaultLoad','vaultOpen'])assert.ok(ui.includes('function '+fn),'Vault UI must implement '+fn);
for(const label of ['Export / Download','Share','Print'])assert.ok(ui.includes(label),'Vault must expose '+label);
console.log('Private document vault checks passed: owner-authenticated metadata, private bucket, SHA-256 integrity, bounded formats, signed downloads and export/share/print UI.');
