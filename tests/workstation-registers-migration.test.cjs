'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const migration=fs.readFileSync(path.join(root,'supabase/migrations/20261030_workstation_registers.sql'),'utf8');
const membership=fs.readFileSync(path.join(root,'supabase/migrations/20261023_patient_trends.sql'),'utf8');
const api=fs.readFileSync(path.join(root,'api/clinical-cloud.js'),'utf8');
const ui=fs.readFileSync(path.join(root,'workstation-registers.js'),'utf8');
assert.match(migration,/create table if not exists public\.clinic_workstation_registers/i);
assert.match(migration,/register_type in\s*\('daily','death','stock'\)/i);
assert.match(migration,/alter table public\.clinic_workstation_registers enable row level security/i);
assert.match(migration,/alter table public\.clinic_workstation_registers force row level security/i);
assert.match(migration,/revoke all on public\.clinic_workstation_registers from anon, authenticated/i);
assert.match(migration,/grant select, insert, update on public\.clinic_workstation_registers to authenticated/i);
assert.doesNotMatch(migration,/grant\s+[^;]*delete[^;]*on public\.clinic_workstation_registers/i,'Register migration must not grant DELETE');
assert.doesNotMatch(migration,/for delete to/i,'Register migration must not create a DELETE policy');
for(const operation of ['reads','inserts','updates'])assert.match(migration,new RegExp('create policy clinic_register_owner_'+operation,'i'));
assert.match(migration,/owner_id=\(select auth\.uid\(\)\)/i);
assert.match(migration,/exists\s*\(select 1 from public\.clinic_members where user_id=\(select auth\.uid\(\)\)\)/i);
assert.match(membership,/create table public\.clinic_members\s*\(user_id uuid primary key references auth\.users\(id\)\)/i);
assert.match(membership,/revoke all on public\.clinic_members from anon,authenticated/i);
assert.doesNotMatch(membership,/grant\s+insert[^;]*on public\.clinic_members/i,'No client-side membership self-enrolment');
assert.match(membership,/using\s*\(user_id=\(select auth\.uid\(\)\)\)/i);
assert.match(api,/if\(user\.id!==env\.CLINIC_OWNER_USER_ID\)/i,'API must reject non-owner sessions before register routes');
assert.match(api,/register-save/);assert.match(api,/revision=eq\.'/,'Register edits must use optimistic revision checks');
assert.match(ui,/No delete action is provided/i);
assert.match(ui,/clinic-owner-signed-out/,'Signing out clears in-page register data');
console.log('Register migration static checks passed: RLS enabled/forced, member-gated owner_id policies, no client membership enrollment, no DELETE, API owner check and revision-checked UI. Live Supabase migration/RLS still requires a dedicated test database.');
