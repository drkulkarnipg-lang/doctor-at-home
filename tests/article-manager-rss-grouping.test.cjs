'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),{JSDOM}=require('jsdom');
const source=fs.readFileSync('index.html','utf8'),start=source.indexOf('function switchDocTab(tabId)'),end=source.indexOf('function switchClinicalDocView',start);
assert.ok(start>=0&&end>start,'Extract the real workstation tab switcher');
const functionSource=source.slice(start,end)+'\nwindow.switchDocTab=switchDocTab;';
const views=['rxPad','symptomChecker','journalsHub','pathCheatSheet','pathReq','radReq','clinicalCertificates','legalForms','drugDir','articlesHub','settingsTab','clinicalCalculators','everydayTools','chart20','invoice','registers','clinicalTools'];
const dom=new JSDOM(source,{runScripts:'outside-only',url:'https://clinic.example.test/'}),w=dom.window;
w.eval(functionSource);
const research=w.document.getElementById('viewJournalsHub'),articles=w.document.getElementById('viewArticlesHub');
assert.ok(research&&articles,'both Article Manager and dedicated RSS panels must exist');
const originalParent=research.parentElement;
assert.notEqual(originalParent,articles,'the source layout starts with the RSS panel in its own dedicated workstation position');
const visibleTopLevel=()=>views.filter(v=>{const el=w.document.getElementById('view'+v[0].toUpperCase()+v.slice(1));return !articles.contains(el)&&!el.classList.contains('hidden');});
w.switchDocTab('articlesHub');
assert.equal(research.parentElement,articles,'Article Manager must mount the RSS/evidence panel inside its own section');
assert.deepEqual(visibleTopLevel(),['articlesHub'],'Article Manager must be the only visible top-level workstation section');
assert.equal(research.classList.contains('hidden'),false,'embedded RSS panel must be visible inside Article Manager');
w.switchDocTab('journalsHub');
assert.equal(research.parentElement,originalParent,'the dedicated RSS tab must return the panel to its original workstation position');
assert.deepEqual(visibleTopLevel(),['journalsHub'],'the dedicated RSS tab must be the only visible top-level workstation section');
assert.equal(articles.classList.contains('hidden'),true,'Article Manager must not remain visible behind the dedicated RSS tab');
w.switchDocTab('articlesHub');
assert.equal(research.parentElement,articles,'switching back must remount RSS inside Article Manager');
assert.deepEqual(visibleTopLevel(),['articlesHub'],'switching back must not expose a second workstation section');
w.switchDocTab('clinicalTools');
assert.deepEqual(visibleTopLevel(),['clinicalTools'],'Workstation Home remains separate after both RSS directions');
w.switchDocTab('rxPad');
assert.deepEqual(visibleTopLevel(),['rxPad'],'other tabs still switch normally without exposing unrelated panels');
w.close();console.log('Article Manager / RSS grouping checks passed: embedded panel and dedicated tab are isolated in both switching directions.');
