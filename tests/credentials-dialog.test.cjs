'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const dom = new JSDOM(fs.readFileSync('index.html', 'utf8'), {runScripts:'outside-only', url:'https://clinic.example/'});
const w = dom.window, d = w.document;
w.switchDocTab = () => {};
w.renderPublishedArticles = () => {};
w.PatientEducation = require('../patient-education-data.js');
w.eval(fs.readFileSync('preserved-features.js', 'utf8'));
const modal = d.getElementById('credentialsModal');
const opener = [...d.querySelectorAll('button')].find(e => e.textContent.includes('Qualifications & registration'));
const close = modal.querySelector('button');
w.HTMLElement.prototype.getClientRects = function () { return [{}]; };
assert.equal(modal.getAttribute('role'), 'dialog');
assert.equal(d.getElementById(modal.getAttribute('aria-labelledby')).textContent, 'Doctor Credentials & Registration');
assert.match(close.getAttribute('aria-label'), /Close qualifications/);
opener.focus(); w.openCredentialsModal();
assert.equal(d.activeElement, close);
assert.equal(d.body.style.overflow, 'hidden');
const tab = new w.KeyboardEvent('keydown', {key:'Tab', bubbles:true, cancelable:true});
close.dispatchEvent(tab); assert.equal(tab.defaultPrevented, true); assert.equal(d.activeElement, close);
const shiftTab = new w.KeyboardEvent('keydown', {key:'Tab', shiftKey:true, bubbles:true, cancelable:true});
close.dispatchEvent(shiftTab); assert.equal(shiftTab.defaultPrevented, true); assert.equal(d.activeElement, close);
close.dispatchEvent(new w.KeyboardEvent('keydown', {key:'Escape', bubbles:true, cancelable:true}));
assert.ok(modal.classList.contains('hidden')); assert.equal(d.activeElement, opener); assert.equal(d.body.style.overflow, '');
w.openCredentialsModal(); modal.click(); assert.ok(modal.classList.contains('hidden')); assert.equal(d.activeElement, opener);
w.openCredentialsModal(); close.addEventListener('click', w.closeCredentialsModal); close.click();
assert.ok(modal.classList.contains('hidden')); assert.equal(d.activeElement, opener);
dom.window.close();
console.log('Qualifications dialog: accessible name, initial focus, Tab/Shift+Tab containment, Escape, backdrop, close and focus restoration pass.');
