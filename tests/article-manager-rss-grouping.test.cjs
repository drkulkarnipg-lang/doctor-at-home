'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),{JSDOM}=require('jsdom');
const source=fs.readFileSync('index.html','utf8'),start=source.indexOf('function switchDocTab(tabId)'),end=source.indexOf('function switchClinicalDocView',start);
assert.ok(start>=0&&end>start,'Extract the real workstation tab switcher');
const functionSource=source.slice(start,end)+'\nwindow.switchDocTab=switchDocTab;';
const views=['rxPad','symptomChecker','journalsHub','pathCheatSheet','pathReq','radReq','clinicalCertificates','legalForms','drugDir','articlesHub','settingsTab','clinicalCalculators','everydayTools','chart20','invoice','registers','clinicalTools'];
const markup='<main>'+views.map(v=>'<section id="view'+v[0].toUpperCase()+v.slice(1)+'" class="hidden"></section>').join('')+'</main>';
const dom=new JSDOM(markup,{runScripts:'outside-only',url:'https://clinic.example.test/'}),w=dom.window;
w.eval(functionSource);
const visible=()=>views.filter(v=>!w.document.getElementById('view'+v[0].toUpperCase()+v.slice(1)).classList.contains('hidden'));
w.switchDocTab('articlesHub');
assert.deepEqual(visible(),['journalsHub','articlesHub'],'Article Manager must show both the article editor and the live RSS/evidence-agent panel');
w.switchDocTab('journalsHub');
assert.deepEqual(visible(),['journalsHub'],'Dedicated RSS tab remains available on its own');
w.switchDocTab('clinicalTools');
assert.deepEqual(visible(),['clinicalTools'],'Workstation Home remains a separate navigation directory');
w.switchDocTab('rxPad');
assert.deepEqual(visible(),['rxPad'],'Other tabs still switch normally without exposing unrelated panels');
w.close();console.log('Article Manager / RSS grouping checks passed: RSS remains available in Article Manager and as its dedicated tab.');
